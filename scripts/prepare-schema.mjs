#!/usr/bin/env node
/**
 * 从唯一事实源 prisma/schema.prisma 生成指定数据库 provider 的 Schema。
 *
 * 只替换 datasource 的 provider 一行，不改动任何模型语义。
 * 产物位于 prisma/.generated/（已 gitignore），避免在仓库里维护第二份 Schema。
 *
 * 用法：
 *   node scripts/prepare-schema.mjs --target postgresql
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SUPPORTED_TARGETS = ['sqlite', 'postgresql'];
const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const targetIndex = process.argv.indexOf('--target');
const target = targetIndex >= 0 ? process.argv[targetIndex + 1] : 'sqlite';

if (!SUPPORTED_TARGETS.includes(target)) {
  console.error(
    `[prepare-schema] 不支持的 target: ${target ?? '(空)'}；可选值: ${SUPPORTED_TARGETS.join(', ')}`
  );
  process.exit(1);
}

const sourcePath = resolve(rootDir, 'prisma', 'schema.prisma');
const outputDir = resolve(rootDir, 'prisma', '.generated');
const outputPath = resolve(outputDir, `schema.${target}.prisma`);

const source = readFileSync(sourcePath, 'utf8');

// 只替换 datasource 块内的 provider，不能匹配到注释里的 “provider = "sqlite"”。
const datasourceMatch = /datasource\s+\w+\s*\{[\s\S]*?\n\}/.exec(source);

if (!datasourceMatch) {
  console.error(
    `[prepare-schema] ${sourcePath} 中未找到 datasource 块；` +
      '请确认根 Schema 结构完整。'
  );
  process.exit(1);
}

const datasourceBlock = datasourceMatch[0];

// 必须锚定到真正的 provider 行：datasource 块内的注释也可能出现
// provider = "sqlite" / "postgresql"，不能把它们当成实际配置。
const providerLine = /^(\s*)provider\s*=\s*"sqlite"\s*$/m;

if (!providerLine.test(datasourceBlock)) {
  console.error(
    `[prepare-schema] datasource 块中未找到实际的 provider = "sqlite" 行；` +
      '请确认根 Schema 仍以 SQLite 为默认 provider。'
  );
  process.exit(1);
}

const rewrittenBlock = datasourceBlock.replace(
  providerLine,
  `$1provider = "${target}"`
);

const targetProviderLine = new RegExp(
  `^\\s*provider\\s*=\\s*"${target}"\\s*$`,
  'm'
);
if (!targetProviderLine.test(rewrittenBlock)) {
  console.error(
    `[prepare-schema] 生成结果校验失败：datasource 的实际 provider 行未变为 "${target}"。`
  );
  process.exit(1);
}

const rewritten =
  source.slice(0, datasourceMatch.index) +
  rewrittenBlock +
  source.slice(datasourceMatch.index + datasourceBlock.length);
const header =
  `// AUTO-GENERATED by scripts/prepare-schema.mjs from prisma/schema.prisma\n` +
  `// provider = "${target}"；请勿直接编辑本文件。\n\n`;

mkdirSync(outputDir, { recursive: true });
writeFileSync(outputPath, header + rewritten, 'utf8');

console.log(`[prepare-schema] 已生成 ${outputPath}（provider = "${target}"）`);
